'use strict';

/**
 * researchEngine.js
 *
 * Multi-step question answering over one or more documents. Instead of a
 * single "embed → top-k → answer" hop, every question goes through:
 *
 *   1. understand   — rewrite follow-ups into a standalone query (uses history)
 *   2. plan         — deep mode: decompose into focused sub-queries
 *   3. retrieve     — hybrid search per query, fused with Reciprocal Rank Fusion
 *                     and a lexical-overlap boost, balanced across documents
 *   4. synthesize   — stream an answer with inline [n] citations
 *   5. verify       — measure how well the answer is grounded in its citations
 *
 * Follow-up suggestions are generated by the caller *after* the answer is
 * delivered (see suggestFollowUps), so they never delay the response.
 *
 * Each step is streamed to the client as a `step` event, so the UI can show a
 * live research trace rather than an opaque spinner.
 */

const { embedText }      = require('./embedder');
const { queryDocuments } = require('./vectorStore');
const llm                = require('./llm');
const { TOP_K }          = require('../config/env');

const MODES = {
  quick: { candidatesPerQuery: 12, finalSources: Math.max(TOP_K, 5) },
  deep:  { candidatesPerQuery: 10, finalSources: Math.max(TOP_K + 3, 8) },
};

const RRF_K = 60;
const SNIPPET_CHARS = 1200;

// ── Lexical scoring ───────────────────────────────────────────────────────────

const STOPWORDS = new Set((
  'a an and are as at be been but by can could did do does for from had has have how i if in ' +
  'into is it its me my of on or our so than that the their them then there these they this ' +
  'to was we were what when where which who whom why will with would you your about tell ' +
  'explain describe give list show document documents say says said please'
).split(' '));

function terms(text) {
  return [...new Set(
    text.toLowerCase().match(/[a-z0-9][a-z0-9.%$-]*[a-z0-9%]|[a-z0-9]/g) ?? []
  )].filter(t => t.length > 1 && !STOPWORDS.has(t));
}

/** Fraction of query terms that appear in the passage (0–1). */
function lexicalScore(queryTerms, text) {
  if (!queryTerms.length) return 0;
  const hay = text.toLowerCase();
  let hits = 0;
  for (const t of queryTerms) if (hay.includes(t)) hits++;
  return hits / queryTerms.length;
}

// ── Retrieval ─────────────────────────────────────────────────────────────────

/**
 * Hybrid retrieval: dense search for each query, fused with RRF, re-scored
 * with lexical overlap, then balanced so every document in scope is represented.
 */
async function retrieve(queries, docIds, { candidatesPerQuery, finalSources }) {
  const fused = new Map();   // key → candidate

  // Embedding is CPU-bound (sequential); the vector searches are I/O and run
  // concurrently. Results are fused in query order, so ranking is unchanged.
  const vectors = [];
  for (const query of queries) vectors.push(await embedText(query));
  const hitLists = await Promise.all(vectors.map(vec => queryDocuments(docIds, vec, candidatesPerQuery)));

  for (const hits of hitLists) {
    hits.forEach((h, rank) => {
      const key = `${h.documentId}:${h.chunkIndex}`;
      const c = fused.get(key) ?? { ...h, rrf: 0, cosine: 0, matchedQueries: 0 };
      c.rrf += 1 / (RRF_K + rank + 1);
      c.cosine = Math.max(c.cosine, h.score);
      c.matchedQueries++;
      fused.set(key, c);
    });
  }

  if (fused.size === 0) return [];

  const queryTerms = terms(queries.join(' '));
  const candidates = [...fused.values()];
  const maxRrf = Math.max(...candidates.map(c => c.rrf));

  for (const c of candidates) {
    c.lexical = lexicalScore(queryTerms, c.text);
    c.final   = 0.55 * (c.rrf / maxRrf) + 0.30 * Math.max(0, c.cosine) + 0.15 * c.lexical;
  }
  candidates.sort((a, b) => b.final - a.final);

  const selected = candidates.slice(0, finalSources);

  // Multi-document balance: make sure each document with a reasonable
  // candidate gets at least one seat (crucial for comparison questions).
  if (docIds.length > 1) {
    for (const docId of docIds) {
      if (selected.some(c => c.documentId === docId)) continue;
      const best = candidates.find(c => c.documentId === docId && c.cosine > 0.2);
      if (!best) continue;
      // replace the weakest source from an over-represented document
      for (let i = selected.length - 1; i >= 0; i--) {
        const d = selected[i].documentId;
        if (selected.filter(c => c.documentId === d).length > 1) {
          selected[i] = best;
          break;
        }
      }
    }
  }

  // Present in reading order within each document — easier for the LLM to follow
  return selected.sort((a, b) =>
    a.documentId === b.documentId ? a.chunkIndex - b.chunkIndex : b.final - a.final
  );
}

// ── Grounding ─────────────────────────────────────────────────────────────────

const CITATION_RE  = /\[(\d+(?:\s*[,–-]\s*\d+)*)\]/g;
const HAS_CITATION = /\[\d+(?:\s*[,–-]\s*\d+)*\]/;
const NOT_FOUND_RE = /\b(do(?:es)? not (?:contain|cover|mention|provide|include|specify|discuss)|no (?:information|mention|details?)|not (?:mentioned|covered|specified|provided|discussed|found))\b/i;

/** Parse the set of citation numbers used in an answer. */
function citedNumbers(answer, max) {
  const out = new Set();
  for (const m of answer.matchAll(CITATION_RE)) {
    for (const part of m[1].split(',')) {
      const range = part.split(/[–-]/).map(n => parseInt(n, 10));
      const [a, b = a] = range;
      for (let n = a; n <= b && n - a < 20; n++) if (n >= 1 && n <= max) out.add(n);
    }
  }
  return out;
}

/**
 * Estimate how well an answer is supported by its sources.
 * coverage  — share of substantive lines/sentences carrying a citation
 * strength  — average retrieval similarity of the cited passages
 */
function assessGrounding(answer, sources) {
  const cited = citedNumbers(answer, sources.length);

  // "The documents do not cover X. They do discuss Y [1]." — the question
  // itself is unanswered, even though related passages are cited.
  const firstSentence = answer.replace(/^\W*(\*\*[^*]+\*\*:?\s*)?/, '').split(/(?<=[.!?])\s/)[0] ?? '';
  if (NOT_FOUND_RE.test(firstSentence)) {
    return { level: 'none', score: 0, citedCount: cited.size, cited, coverage: 0 };
  }

  if (cited.size === 0) {
    const level = NOT_FOUND_RE.test(answer) ? 'none' : 'low';
    return { level, score: 0, citedCount: 0, cited, coverage: 0 };
  }

  const units = answer
    .split(/\n+|(?<=[.!?])\s+(?=[A-Z])/)
    .map(s => s.trim())
    .filter(s => s.length > 40 && !s.startsWith('#') && !/^\|?\s*-{3,}/.test(s));
  const coverage = units.length
    ? units.filter(u => HAS_CITATION.test(u)).length / units.length
    : 1;

  const citedSources = [...cited].map(n => sources[n - 1]);
  const avgCos = citedSources.reduce((s, c) => s + Math.max(0, c.cosine), 0) / citedSources.length;
  const strength = Math.min(1, avgCos / 0.55);

  const score = Math.round((0.6 * coverage + 0.4 * strength) * 100) / 100;
  const level = score >= 0.7 ? 'high' : score >= 0.45 ? 'medium' : 'low';
  return { level, score, citedCount: cited.size, cited, coverage };
}

// ── Orchestrator ──────────────────────────────────────────────────────────────

/**
 * Run the research pipeline, yielding events as it goes.
 *
 * @param {object}   p
 * @param {string}   p.question
 * @param {{ role, content }[]} p.history   prior turns (NOT including this question)
 * @param {{ id:string, name:string }[]} p.documents   documents in scope
 * @param {'quick'|'deep'} [p.mode]
 *
 * Yields:
 *   { type: 'step',    data: { id, kind, label, status, detail?, items?, durationMs? } }
 *   { type: 'sources', data: Source[] }
 *   { type: 'token',   data: { delta } }
 *   { type: 'result',  data: { content, sources, trace, grounding, mode } }
 */
async function* research({ question, history = [], documents, mode = 'quick' }) {
  const cfg    = MODES[mode] ?? MODES.quick;
  const docIds = documents.map(d => d.id);
  const nameOf = Object.fromEntries(documents.map(d => [d.id, d.name]));
  const trace  = [];

  // Small helper to time a step and emit running/done events
  let stepNo = 0;
  const begin = (kind, label) => {
    const step = { id: `s${++stepNo}`, kind, label, status: 'running', t0: Date.now() };
    return { step, event: { type: 'step', data: { id: step.id, kind, label, status: 'running' } } };
  };
  const finish = (step, extra = {}) => {
    const done = {
      id: step.id, kind: step.kind, label: extra.label ?? step.label, status: 'done',
      detail: extra.detail ?? '', items: extra.items ?? [], durationMs: Date.now() - step.t0,
    };
    trace.push({ kind: done.kind, label: done.label, detail: done.detail, items: done.items, durationMs: done.durationMs });
    return { type: 'step', data: done };
  };

  // 1 ── Understand ───────────────────────────────────────────────────────────
  let s = begin('understand', 'Understanding the question');
  yield s.event;
  const standalone = await llm.rewriteQuery(question, history);
  yield finish(s.step, {
    detail: standalone !== question ? `Interpreted as: “${standalone}”` : 'Question is self-contained',
  });

  // 2 ── Plan (deep mode) ─────────────────────────────────────────────────────
  let plan = [];
  if (mode === 'deep') {
    s = begin('plan', 'Planning the research');
    yield s.event;
    plan = await llm.planQueries(standalone, documents.map(d => d.name));
    yield finish(s.step, {
      label:  `Planned ${plan.length} lines of inquiry`,
      items:  plan,
    });
  }

  // 3 ── Retrieve ─────────────────────────────────────────────────────────────
  const queries = [...new Set([standalone, ...plan])];
  s = begin('retrieve', documents.length > 1
    ? `Searching ${documents.length} documents`
    : 'Searching the document');
  yield s.event;

  const hits = await retrieve(queries, docIds, cfg);
  const sources = hits.map((h, i) => ({
    index:        i + 1,
    documentId:   h.documentId,
    documentName: nameOf[h.documentId] ?? 'Document',
    pageNumber:   h.pageNumber,
    pageEnd:      h.pageEnd,
    chunkIndex:   h.chunkIndex,
    text:         h.text,
    cosine:       h.cosine,
  }));

  const docsHit = new Set(sources.map(x => x.documentId)).size;
  const pages   = [...new Set(sources.map(x => x.pageNumber))].sort((a, b) => a - b);
  yield finish(s.step, {
    detail: sources.length
      ? `Found ${sources.length} relevant passages` +
        (documents.length > 1 ? ` across ${docsHit} of ${documents.length} documents` : '') +
        ` · pages ${pages.slice(0, 8).join(', ')}${pages.length > 8 ? '…' : ''}`
      : 'No matching passages found',
    items: queries.length > 1 ? queries : [],
  });

  // Let the UI resolve citations while the answer streams
  const publicSources = sources.map(x => ({
    index:        x.index,
    documentId:   x.documentId,
    documentName: x.documentName,
    pageNumber:   x.pageNumber,
    pageEnd:      x.pageEnd,
    chunkIndex:   x.chunkIndex,
    snippet:      x.text.slice(0, SNIPPET_CHARS),
    score:        Math.min(1, Math.max(0, Math.round(x.cosine * 1000) / 1000)),
    cited:        false,
  }));
  yield { type: 'sources', data: publicSources };

  // 4 ── Synthesize ───────────────────────────────────────────────────────────
  s = begin('synthesize', 'Writing a cited answer');
  yield s.event;

  let content = '';
  if (sources.length === 0) {
    content = documents.length > 1
      ? 'I couldn\'t find anything in the selected documents related to this question.'
      : 'I couldn\'t find anything in this document related to this question.';
    yield { type: 'token', data: { delta: content } };
  } else {
    // Retry provider rate limits (common on free tiers) as long as nothing
    // has been streamed yet — the wait is shown live in the trace.
    for (let attempt = 0; ; attempt++) {
      try {
        for await (const delta of llm.streamAnswer({ question, sources, history, mode, plan })) {
          content += delta;
          yield { type: 'token', data: { delta } };
        }
        break;
      } catch (err) {
        const wait = llm.rateLimitDelay(err);
        if (wait == null || content || attempt >= 2) throw err;
        yield { type: 'step', data: {
          id: s.step.id, kind: 'synthesize', status: 'running',
          label: `Waiting for model capacity (${Math.ceil(wait / 1000)}s)…`,
        } };
        await new Promise(r => setTimeout(r, wait));
        yield { type: 'step', data: { id: s.step.id, kind: 'synthesize', status: 'running', label: s.step.label } };
      }
    }
  }
  content = content.trim();

  // 5 ── Verify ───────────────────────────────────────────────────────────────
  const grounding = assessGrounding(content, sources);
  publicSources.forEach(src => { src.cited = grounding.cited.has(src.index); });

  yield finish(s.step, {
    detail: grounding.citedCount
      ? `Cited ${grounding.citedCount} of ${sources.length} passages`
      : 'No passages cited',
  });

  s = begin('verify', 'Checking the answer against sources');
  yield s.event;
  const levelLabel = { high: 'Well grounded', medium: 'Partially grounded', low: 'Weakly grounded', none: 'Not covered by the documents' };
  yield finish(s.step, {
    detail: grounding.level === 'none' || grounding.level === 'low'
      ? levelLabel[grounding.level]
      : `${levelLabel[grounding.level]} · ${Math.round(grounding.coverage * 100)}% of statements carry a citation`,
  });

  yield {
    type: 'result',
    data: {
      content,
      mode,
      sources: publicSources,
      trace,
      grounding: { level: grounding.level, score: grounding.score, citedCount: grounding.citedCount },
    },
  };
}

/**
 * Follow-up questions for a finished answer. Never throws.
 * @param {string} question
 * @param {{ content:string, sources:{ snippet:string }[] }} result
 */
async function suggestFollowUps(question, result) {
  if (!result.sources?.length || result.grounding?.level === 'none') return [];
  return llm.suggestFollowUps(
    question, result.content, result.sources.map(s => ({ text: s.snippet }))
  ).catch(() => []);
}

module.exports = { research, suggestFollowUps, assessGrounding, citedNumbers, retrieve };
